async function updateSmartAssistantPrompt() {
  const connection = await mysql.createConnection(process.env.DATABASE_URL);
  
  try {
    console.log("开始更新智能AI助手的systemPrompt...");
    
    // 查找智能AI助手
    const [rows] = await connection.execute(
      "SELECT id FROM agents WHERE name = ?",
      ['智能AI助手']
    );
    
    if (rows.length === 0) {
      console.error("❌ 未找到智能AI助手");
      process.exit(1);
    }
    
    const agentId = rows[0].id;
    console.log(`找到智能AI助手，ID: ${agentId}`);
    
    // 更新systemPrompt
    await connection.execute(
      "UPDATE agents SET systemPrompt = ? WHERE id = ?",
      [newSystemPrompt, agentId]
    );
    
    console.log("✅ 智能AI助手的systemPrompt已更新！");
    console.log("主要变更：移除了所有Markdown链接格式，改用「」中文书名号引用顾问名称");
    
    await connection.end();
    process.exit(0);
  } catch (error) {
    console.error("❌ 更新失败:", error);
    await connection.end();
    process.exit(1);
  }
}

