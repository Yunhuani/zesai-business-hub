/**
 * 根据文件名匹配对应的文档结构
 */
export function getDocumentStructure(fileName: string): string {
  // 移除文件扩展名和特殊字符
  const cleanFileName = fileName
    .replace(/\.(docx|pdf|pptx)$/i, "")
    .replace(/[（(].*?[）)]/g, "")
    .trim();

  // 精确匹配
  for (const [key, structure] of Object.entries(DOCUMENT_STRUCTURES)) {
    if (cleanFileName.includes(key) || key.includes(cleanFileName)) {
      return structure;
    }
  }

  // 关键词匹配
  const keywordMap: Record<string, string> = {
    战略: "战略规划",
    规划: "战略规划",
    BP: "商业计划书",
    商业计划: "商业计划书",
  };

  for (const [keyword, structureKey] of Object.entries(keywordMap)) {
    if (cleanFileName.includes(keyword)) {
      return DOCUMENT_STRUCTURES[structureKey as keyof typeof DOCUMENT_STRUCTURES];
    }
  }

  // 默认结构
  return DOCUMENT_STRUCTURES.default;
}
